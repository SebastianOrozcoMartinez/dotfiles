#!/bin/sh
set -e

WAL="$HOME/.cache/wal/colors.json"
OB_APPEARANCE="$HOME/Documents/VoidVault/.obsidian/appearance.json"
OB_FILECOLOR="$HOME/Documents/VoidVault/.obsidian/plugins/obsidian-file-color/data.json"
OB_COLORTAGS="$HOME/Documents/VoidVault/.obsidian/plugins/colored-tags/data.json"
OB_SNIPPET="$HOME/Documents/VoidVault/.obsidian/snippets/pywal.css"

[ -f "$WAL" ] || exit 1
[ -f "$OB_APPEARANCE" ] || exit 1
[ -f "$OB_FILECOLOR" ] || exit 1
[ -f "$OB_COLORTAGS" ] || exit 1

ACCENT=$(jq -r '.colors.color3' "$WAL")

tmp=$(mktemp)
tmp2=$(mktemp)
tmp3=$(mktemp)
tmp4=$(mktemp)
trap 'rm -f "$tmp" "$tmp2" "$tmp3" "$tmp4"' EXIT

# Accent color (no mercy)
# Also keep the pywal snippet enabled, otherwise the CSS below goes nowhere.
jq --arg accent "$ACCENT" '
  .accentColor = $accent
  | .enabledCssSnippets = (((.enabledCssSnippets // []) + ["pywal"]) | unique)
' "$OB_APPEARANCE" >"$tmp" && mv "$tmp" "$OB_APPEARANCE"

# File-color plugin (blind overwrite, no fallback, no questions asked)
jq --slurpfile wal "$WAL" '
  .palette |= map(
    . as $entry |
    ($entry.name) as $colorname |
    .value = $wal[0].colors[$colorname]
  )
' "$OB_FILECOLOR" >"$tmp2" && mv "$tmp2" "$OB_FILECOLOR"

# Colored Tags plugin. Same story as file-color: it kept its own hand-picked
# palette (which had drifted to the theme's old hardcoded fallbacks) and nothing
# ever fed it pywal. Slot count is deliberately kept at 15 so every tag that
# already has an index keeps it -- only the hex behind each slot moves.
#
# The plugin stores the palette as dash-separated hex WITHOUT a leading #, and
# prepends one itself when parsing.
jq --slurpfile wal "$WAL" '
  .palette.custom = (
    [ range(1; 16) | "color\(.)" ]
    | map($wal[0].colors[.])
    | map(ltrimstr("#"))
    | join("-")
  )
' "$OB_COLORTAGS" >"$tmp4" && mv "$tmp4" "$OB_COLORTAGS"

# Raw palette as CSS custom properties, for the Nova theme.
#
# This has to be a generated snippet rather than an @import. Obsidian ships
# `style-src \x27unsafe-inline\x27 \x27self\x27 https://fonts.googleapis.com` and no
# file: scheme, so `@import url("file:///.../colors.css")` is refused by the
# renderer and the vars silently never exist -- which is why the theme used to
# sit on its hardcoded fallbacks no matter what `wal` did.
#
# Obsidian watches .obsidian/snippets/*.css as `appearance-data` and hot-reloads
# it, so the theme follows `wal` live with no restart.
jq -r '
  "/* pywal sync - GENERATED by ~/.config/wal/hooks/obsidian.sh, do not edit.",
  "   Source: ~/.cache/wal/colors.json, rewritten on every `wal` run.",
  "   Values are inlined on purpose: Obsidian CSP does not allow file: in",
  "   style-src, so importing ~/.cache/wal/colors.css would be refused.",
  "   Nova maps these onto --nova-* in themes/Nova/theme.css. */",
  ":root {",
  "  --background: \(.special.background);",
  "  --foreground: \(.special.foreground);",
  "  --cursor: \(.special.cursor);",
  ( .colors
    | to_entries
    | sort_by(.key | ltrimstr("color") | tonumber)[]
    | "  --\(.key): \(.value);"
  ),
  "  --wallpaper: url(\"file://\(.wallpaper)\");",
  "}"
' "$WAL" >"$tmp3" && mv "$tmp3" "$OB_SNIPPET"

# Heading ramp, emitted as a second block appended to the same snippet.
#
# pywal ramps are near-monochromatic, so Maple's colorful-heading mapping
# (red/orange/green/blue/purple/cyan) never tracks the wallpaper -- and naively
# pointing h1..h6 at color1..color6 is just as bad, because those six sit within
# ~60deg of hue. So: keep each pywal color's hue and saturation, force an explicit
# lightness ladder (h1 brightest -> h6 dimmest). The -rgb triples are emitted too
# because CodeMirror reads --hN-color-rgb while reading view uses --hN-color, and
# the two must not disagree.
#
# Tuned so every heading clears 4.5:1 on any wallpaper: h1 is the most prominent
# and h6 the most subdued. Adjust HEADING_CONTRAST to restyle; keep it monotonic
# and keep the last value at or above 4.5.
HEADING_CONTRAST="12.0 9.5 7.5 6.2 5.2 4.6"
HEADING_SRC="6 5 4 3 2 1"
SAT_BOOST=8

python3 - "$WAL" "$HEADING_CONTRAST" "$HEADING_SRC" "$SAT_BOOST" >>"$OB_SNIPPET" <<'PY'
import colorsys, json, sys

colors_path, targets, srcs, boost = sys.argv[1:5]
targets = [float(x) for x in targets.split()]
srcs = [int(x) for x in srcs.split()]
boost = int(boost) / 100.0

with open(colors_path) as fh:
    wal = json.load(fh)

colors = wal["colors"]
bg = wal["special"]["background"]


def rgb(hexstr):
    return tuple(int(hexstr[i:i + 2], 16) / 255 for i in (1, 3, 5))


def triple(hexstr):
    return ", ".join(str(int(hexstr[i:i + 2], 16)) for i in (1, 3, 5))


def luminance(rgbval):
    out = []
    for v in rgbval:
        out.append(v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4)
    r, g, b = out
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def to_hex(rgbval):
    return "#%02X%02X%02X" % tuple(round(c * 255) for c in rgbval)


bg_rgb = rgb(bg)

# A fixed HSL lightness ladder is not hue-robust: relative luminance depends on
# hue, so a saturated blue at the same HSL lightness as a green lands much
# darker and can drop under 4.5:1. Solve for the *lowest* deviation from the
# pywal colour that still hits each contrast target instead -- that keeps the
# colour as saturated as possible while guaranteeing readability against
# whatever the wallpaper picked.
#
# The direction is not always "lighter": a scheme can hand us a mid or light
# background where darkening is the only way to gain contrast. Bisect toward
# whichever end actually helps.
#
# A mid-tone background also caps how much contrast is reachable at all (against
# a background of luminance L the ceiling is max((1.05)/(L+0.05),
# (L+0.05)/(0.05))), so when the top target is physically out of reach, rescale
# the whole ladder into the available band. Otherwise the unreachable headings
# all pile up on the ceiling and the h1..h3 hierarchy collapses.
def solve(hue, sat, target):
    lightest = colorsys.hls_to_rgb(hue, 1.0, sat)
    darkest = colorsys.hls_to_rgb(hue, 0.0, sat)
    if contrast(lightest, bg_rgb) >= contrast(darkest, bg_rgb):
        lo, hi = 0.0, 1.0
    else:
        lo, hi = 1.0, 0.0
    for _ in range(40):
        mid = (lo + hi) / 2
        if contrast(colorsys.hls_to_rgb(hue, mid, sat), bg_rgb) >= target:
            hi = mid
        else:
            lo = mid
    return colorsys.hls_to_rgb(hue, hi, sat)


best = []
for idx in srcs:
    h, _, s = colorsys.rgb_to_hls(*rgb(colors["color%d" % idx]))
    sat = min(1.0, s + boost)
    best.append(max(contrast(colorsys.hls_to_rgb(h, 1.0, sat), bg_rgb),
                    contrast(colorsys.hls_to_rgb(h, 0.0, sat), bg_rgb)))

ceiling = min(best)
if max(targets) > ceiling:
    floor_ = min(targets)
    span = len(targets) - 1
    targets = [ceiling - (ceiling - floor_) * i / span for i in range(len(targets))]


print()
print("/* heading ramp: pywal hue+sat, lightness solved for a contrast target */")
print(":root {")
for n, (target, idx) in enumerate(zip(targets, srcs), start=1):
    h, _, s = colorsys.rgb_to_hls(*rgb(colors["color%d" % idx]))
    hexstr = to_hex(solve(h, min(1.0, s + boost), target))
    print("  --nova-h%d: %s;  /* color%d, %.1f:1 */" % (n, hexstr, idx, contrast(rgb(hexstr), bg_rgb)))
    print("  --nova-h%d-rgb: %s;" % (n, triple(hexstr)))
print("}")
PY

# Raw -rgb triples for every pywal color. The theme leans on Obsidian's
# --color-*-rgb convention in a lot of places, so keep both forms available.
python3 - "$WAL" >>"$OB_SNIPPET" <<'PY'
import json, sys

with open(sys.argv[1]) as fh:
    colors = json.load(fh)["colors"]

print()
print("/* raw channel triples, for the theme\u0027s --color-*-rgb convention */")
print(":root {")
for key in sorted(colors, key=lambda k: int(k.lstrip("color"))):
    hexstr = colors[key]
    triple = ", ".join(str(int(hexstr[i:i + 2], 16)) for i in (1, 3, 5))
    print("  --%s-rgb: %s;" % (key, triple))
print("}")
PY

# Reload ONLY if obsidian is running. Both plugins bake their palettes into
# rendered inline styles at load, so a data.json write alone is not enough.
if pgrep -f obsidian >/dev/null; then
  obsidian plugin:reload id=obsidian-file-color >/dev/null 2>&1
  obsidian plugin:reload id=colored-tags >/dev/null 2>&1
fi
